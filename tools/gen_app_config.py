#!/usr/bin/env python3
"""Bake the daemon's address and token into the shell APK's resources.

The phone builds the APK and runs the daemon, so there is nothing for a pairing code to
establish -- both halves already share a filesystem. Writing the credentials in at build time
removes the whole exchange: install, open, connected.

The tradeoff, stated plainly: the token sits in the APK, so anyone who can read the APK file
can talk to the daemon. That is the same trust boundary as the device itself, which is why it
is acceptable here and would not be if the APK were ever distributed.

Run from the repo root:  .venv/bin/python tools/gen_app_config.py
"""
from __future__ import annotations

import html
import pathlib
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from forged import config  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
# Every app that talks to the daemon gets the same baked credentials.
OUTS = [ROOT / "forge-app" / "res" / "values" / "config.xml",
        ROOT / "notes-app" / "res" / "values" / "config.xml",
        ROOT / "cable-app" / "res" / "values" / "config.xml"]


def lan_address() -> str:
    """First non-loopback IPv4. The daemon binds 0.0.0.0, so this is how Android reaches it."""
    out = subprocess.run(["hostname", "-I"], capture_output=True, text=True).stdout
    for candidate in out.split():
        if candidate and not candidate.startswith("127."):
            return candidate
    return "127.0.0.1"


def main() -> None:
    host = f"{lan_address()}:{config.PORT}"
    token = config.load_token()

    for OUT in OUTS:
        if not OUT.parent.parent.parent.exists():
            continue
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- Generated by tools/gen_app_config.py. Do not edit; never commit a token. -->\n"
            "<resources>\n"
            f'    <string name="default_host">{html.escape(host)}</string>\n'
            f'    <string name="default_token">{html.escape(token)}</string>\n'
            "</resources>\n"
        )
        print(f"wrote {OUT} (host={host})")


if __name__ == "__main__":
    main()
